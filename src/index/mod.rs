/// Default port for the embedded service-directory index server.
const DEFAULT_INDEX_PORT: u16 = 18080;

static CURRENT_INDEX_PORT: std::sync::atomic::AtomicU16 = std::sync::atomic::AtomicU16::new(0);

/// Default number of trailing lines served by the live-log stream.
const DEFAULT_LOG_TAIL: usize = 200;
/// Upper bound for the `tail` query parameter, so a single request cannot
/// request an unbounded backfill.
const MAX_LOG_TAIL: usize = 10_000;

/// HTTP response body used by the embedded server. Static pages and the SSE
/// log stream both box into this type so a single service fn serves them all.
type RespBody = BoxBody<Bytes, Infallible>;

/// One reachable service discovered from docker (Traefik labels or
/// `fog.expose` custom labels).
#[derive(Clone)]
struct IndexEntry {
    /// Display project name (e.g. `gems`, `red-fox`), derived from the repo
    /// root of the compose project's working dir.
    project: String,
    /// Worktree/branch group (e.g. `main`, `feature-x`). Shared infra services
    /// report `shared`.
    worktree: String,
    #[allow(dead_code)]
    /// Whether this is a shared infra service (under the `shared` subgroup).
    shared: bool,
    /// Docker container name (e.g. `redfox-main-api-1`), used to stream that
    /// container's logs.
    container: String,
    /// Compose service name (e.g. `frontend`, `postgres`).
    service: String,
    /// Hostname the router accepts (e.g. `main.red-fox`, `main.postgres.gems`).
    hostname: String,
    /// Internal container port Traefik forwards to. Empty for raw-TCP
    /// services exposed via `fog.expose` (they are reached by host port).
    port: String,
    /// Host-published docker port bindings of the container (e.g.
    /// `0.0.0.0:8080->8080/tcp`). Empty when nothing is published to the host.
    published: Vec<String>,
    /// The host port number docker published for this service, if any
    /// (e.g. `53012` for `0.0.0.0:53012->5173/tcp`).
    raw_port: Option<String>,
    /// Whether the router terminates TLS (`https`) or not (`http`).
    tls: bool,
}

/// Ensures the standalone index server is running. Idempotent and best-effort.
pub fn ensure(cfg: &RouterConfig) -> Vec<String> {
    ensure_with_router(cfg)
}

/// Ensures the index server for a full `Config`, respecting `index.enabled`
/// (default `true`) in both fog config (`~/.config/fog/fog.json` with `theme`)
/// and per-project `fog.json`. Either can opt-out. When disabled, no server
/// is started.
pub fn ensure_for_config(cfg: &crate::config::Config) -> Vec<String> {
    if !cfg.effective_should_serve_index() {
        return Vec::new();
    }
    let port = cfg.effective_index_port();
    let network = cfg.index_network();
    ensure_with_port(port, &network)
}

fn ensure_with_router(cfg: &RouterConfig) -> Vec<String> {
    let mut messages = Vec::new();
    if !command_exists("docker") {
        return messages;
    }
    let port = cfg.index_port.unwrap_or(DEFAULT_INDEX_PORT);
    if server_started(port) {
        return messages;
    }
    match spawn_server(cfg) {
        Ok(()) => messages.push(format!(
            "  + service index server on http://127.0.0.1:{port}"
        )),
        Err(e) => messages.push(format!("⚠ could not start index server on :{port} ({e})")),
    }
    messages
}

pub fn ensure_with_port(port: u16, network: &str) -> Vec<String> {
    let mut messages = Vec::new();
    if !command_exists("docker") {
        return messages;
    }
    if server_started(port) {
        return messages;
    }
    // Build a minimal RouterConfig for spawn_server.
    let cfg = RouterConfig {
        index_port: Some(port),
        shared_network: network.to_string(),
        ..Default::default()
    };
    match spawn_server(&cfg) {
        Ok(()) => messages.push(format!(
            "  + service index server on http://127.0.0.1:{port}"
        )),
        Err(e) => messages.push(format!("⚠ could not start index server on :{port} ({e})")),
    }
    messages
}

/// Whether the standalone index server is already listening.
fn server_started(port: u16) -> bool {
    std::net::TcpStream::connect(("127.0.0.1", port)).is_ok()
}

/// Public check whether the index server is listening on `port`.
pub fn is_server_started(port: u16) -> bool {
    server_started(port)
}

/// Path to the pidfile for the index server on `port`.
fn index_pid_path(port: u16) -> PathBuf {
    std::env::temp_dir().join(format!("fog-index-{port}.pid"))
}

/// Best-effort: terminate the index server on `port` if it is running.
///
/// Returns `true` if the server was stopped (or was not running).
fn terminate_server_on_port(port: u16) -> bool {
    // Prefer the pidfile, but fall back to a port probe.
    let pid: Option<u32> = std::fs::read_to_string(index_pid_path(port))
        .ok()
        .and_then(|s| s.trim().parse().ok());

    if let Some(pid) = pid {
        // If the pid is our own, don't signal ourselves — just clean up.
        if pid != std::process::id() && crate::process::is_pid_alive(pid) {
            let _ = crate::process::kill_process(pid, crate::process::Signal::Term);
            crate::process::try_kill_process_group(pid, crate::process::Signal::Term);
            // Give it a moment to exit gracefully.
            for _ in 0..20 {
                if !crate::process::is_pid_alive(pid) || !server_started(port) {
                    break;
                }
                std::thread::sleep(std::time::Duration::from_millis(100));
            }
            if crate::process::is_pid_alive(pid) && server_started(port) {
                let _ = crate::process::kill_process(pid, crate::process::Signal::Kill);
                crate::process::try_kill_process_group(pid, crate::process::Signal::Kill);
                std::thread::sleep(std::time::Duration::from_millis(200));
            }
        }
        let _ = std::fs::remove_file(index_pid_path(port));
        // Even if the pid was stale, consider it handled if the port is now closed.
        // For self-pid, the port is still open until we exit, so return true
        // to indicate the pidfile was handled; the caller will exit separately.
        if pid == std::process::id() {
            return true;
        }
        return !server_started(port);
    }

    // No pidfile: if nothing is listening we are already done.
    if !server_started(port) {
        return true;
    }

    // Fallback: try to discover the pid via lsof/fuser when no pidfile exists
    // (e.g. legacy server started before pidfile logic).
    if let Ok(out) = std::process::Command::new("lsof")
        .args(["-ti", &format!(":{}", port)])
        .output()
    {
        let pids = String::from_utf8_lossy(&out.stdout);
        for pid_str in pids.split_whitespace() {
            if let Ok(pid) = pid_str.parse::<u32>()
                && pid != std::process::id()
                && crate::process::is_pid_alive(pid)
            {
                // Try both process-group and direct kill for compatibility
                // with servers started with and without setsid.
                let _ = crate::process::kill_process(pid, crate::process::Signal::Term);
                crate::process::try_kill_process_group(pid, crate::process::Signal::Term);
                std::thread::sleep(std::time::Duration::from_millis(300));
                if crate::process::is_pid_alive(pid) {
                    let _ = crate::process::kill_process(pid, crate::process::Signal::Kill);
                    crate::process::try_kill_process_group(pid, crate::process::Signal::Kill);
                }
            }
        }
        std::thread::sleep(std::time::Duration::from_millis(300));
        return !server_started(port);
    }

    // Last resort: try to find `fog index serve` via `ps` is fragile; just
    // report failure and let the caller retry via polling self-exit.
    false
}

/// Kill the index server on `port` if no fog instances remain.
pub fn maybe_terminate_on_port(port: u16) {
    let instances = crate::ipc::find_instances().unwrap_or_default();
    let any_alive = instances
        .iter()
        .any(|(_, p)| crate::ipc::query_status(p).is_ok());
    if any_alive {
        return;
    }
    let _ = terminate_server_on_port(port);
    if port != DEFAULT_INDEX_PORT {
        let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
    }
}

/// Kill the index server for a full `Config` if no instances remain.
pub fn maybe_terminate_for_config(cfg: &crate::config::Config) {
    maybe_terminate_on_port(cfg.index_port());
}

/// Kill the index server if no fog instances remain.
///
/// Looks at `crate::ipc::find_instances()`. If no instances are alive,
/// attempts to stop the server on the configured port (or the default
/// `18080`). Best-effort and never panics.
pub fn maybe_terminate_if_no_instances(cfg: Option<&RouterConfig>) {
    let instances = crate::ipc::find_instances().unwrap_or_default();
    let any_alive = instances
        .iter()
        .any(|(_, p)| crate::ipc::query_status(p).is_ok());
    if any_alive {
        return;
    }
    // No live instance responded — idle, tear down the server.
    if let Some(c) = cfg {
        let port = c.index_port.unwrap_or(DEFAULT_INDEX_PORT);
        let _ = terminate_server_on_port(port);
        if port != DEFAULT_INDEX_PORT {
            let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
        }
        return;
    }
    // No config given (e.g. `fog kill` without a config): try the default
    // port and any pidfile-discovered custom ports.
    let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
    if let Ok(dir) = std::fs::read_dir(std::env::temp_dir()) {
        for entry in dir.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            if let Some(port_str) = name
                .strip_prefix("fog-index-")
                .and_then(|s| s.strip_suffix(".pid"))
                && let Ok(port) = port_str.parse::<u16>()
                && port != DEFAULT_INDEX_PORT
            {
                let _ = terminate_server_on_port(port);
            }
        }
    }
}

/// Kill the index server for a full `Config` (respects `index.port` then
/// `router.index_port`, plus global fog config fallback).
pub fn kill_for_config(cfg: &crate::config::Config) -> bool {
    let port = cfg.effective_index_port();
    let was_running = server_started(port);
    let _ = terminate_server_on_port(port);
    if port != DEFAULT_INDEX_PORT {
        let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
    }
    was_running && !server_started(port)
}

/// Restart the index server for a full `Config`.
pub fn restart_for_config(cfg: &crate::config::Config) -> Result<u16, String> {
    let _ = kill_for_config(cfg);
    std::thread::sleep(std::time::Duration::from_millis(300));
    ensure_for_config(cfg);
    let port = cfg.effective_index_port();
    if server_started(port) {
        return Ok(port);
    }
    Err(format!("server did not start on :{port}"))
}

/// Unconditionally kill the index server on `port` (or default when `cfg` is
/// `None`). Returns `true` if a server was running and is now stopped.
pub fn kill_server(cfg: Option<&RouterConfig>) -> bool {
    if let Some(c) = cfg {
        let port = c.index_port.unwrap_or(DEFAULT_INDEX_PORT);
        let was_running = server_started(port);
        let _ = terminate_server_on_port(port);
        if port != DEFAULT_INDEX_PORT {
            let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
        }
        return was_running && !server_started(port);
    }
    let was_running = server_started(DEFAULT_INDEX_PORT);
    let _ = terminate_server_on_port(DEFAULT_INDEX_PORT);
    // Also kill any custom-port servers discovered via pidfiles.
    if let Ok(dir) = std::fs::read_dir(std::env::temp_dir()) {
        for entry in dir.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            if let Some(port_str) = name
                .strip_prefix("fog-index-")
                .and_then(|s| s.strip_suffix(".pid"))
                && let Ok(port) = port_str.parse::<u16>()
                && port != DEFAULT_INDEX_PORT
            {
                let _ = terminate_server_on_port(port);
            }
        }
    }
    was_running && !server_started(DEFAULT_INDEX_PORT)
}

/// Kill then re-ensure the index server, returning the port it now serves on.
pub fn restart_server(cfg: Option<&RouterConfig>) -> Result<u16, String> {
    let _ = kill_server(cfg);
    // Give the OS a moment to release the port.
    std::thread::sleep(std::time::Duration::from_millis(300));
    if let Some(c) = cfg {
        ensure(c);
        let port = c.index_port.unwrap_or(DEFAULT_INDEX_PORT);
        if server_started(port) {
            return Ok(port);
        }
        // Fallback: ensure with a minimal config on the default port.
        let fallback = RouterConfig {
            shared_network: c.shared_network.clone(),
            ..Default::default()
        };
        ensure(&fallback);
        let port = fallback.index_port.unwrap_or(DEFAULT_INDEX_PORT);
        if server_started(port) {
            return Ok(port);
        }
        return Err(format!("server did not start on :{port}"));
    }
    // No config: start with defaults on 18080.
    let fallback = RouterConfig::default();
    ensure(&fallback);
    let port = fallback.index_port.unwrap_or(DEFAULT_INDEX_PORT);
    if server_started(port) {
        Ok(port)
    } else {
        Err(format!("server did not start on :{port}"))
    }
}

/// Directory holding a background index server's captured output:
/// `$TMPDIR/fog-index-<port>.logs/`. The detached server's own diagnostics
/// go to `daemon.log` inside it.
pub fn index_log_dir(port: u16) -> PathBuf {
    std::env::temp_dir().join(format!("fog-index-{port}.logs"))
}

/// Restricts `path` to owner-only permissions (`mode`) on Unix; no-op
/// elsewhere. Mirrors [`crate::ipc::ensure_instance_dir`], so an index log in
/// the shared temp dir is not readable by other local users.
#[cfg(unix)]
fn restrict_permissions(path: &Path, mode: u32) {
    use std::os::unix::fs::PermissionsExt;
    if let Ok(meta) = std::fs::metadata(path) {
        let mut perms = meta.permissions();
        perms.set_mode(mode);
        let _ = std::fs::set_permissions(path, perms);
    }
}

/// Restricts `path` to owner-only permissions (`mode`) on Unix; no-op
/// elsewhere.
#[cfg(not(unix))]
fn restrict_permissions(_path: &Path, _mode: u32) {}

/// Resolves the port for `fog index serve`: explicit `--port` wins, then
/// `FOG_INDEX_PORT`, then the effective config port (project/global fallback),
/// then the default.
pub fn resolve_serve_port(explicit: Option<u16>) -> u16 {
    if let Some(p) = explicit {
        return p;
    }
    if let Ok(p) = std::env::var("FOG_INDEX_PORT")
        && let Ok(p) = p.parse::<u16>()
    {
        return p;
    }
    load_runtime_config().effective_index_port()
}

/// Resolves the docker network for `fog index serve`: `FOG_INDEX_NETWORK`
/// wins, then the runtime config.
pub fn resolve_serve_network() -> String {
    std::env::var("FOG_INDEX_NETWORK")
        .ok()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| load_runtime_config().index_network())
}

/// Launches the index server as a detached background process (`fog index
/// serve --foreground` as the child), so it survives the launching shell.
/// The child's stdout/stderr go to `daemon.log` in [`index_log_dir`].
/// If it is already running this is a no-op reporting the existing server.
pub fn serve_detached(port: u16, network: &str) -> io::Result<()> {
    if server_started(port) {
        println!("index server already running on :{port}");
        println!("  status: curl http://127.0.0.1:{port}/api/services");
        return Ok(());
    }
    let log_dir = index_log_dir(port);
    std::fs::create_dir_all(&log_dir).map_err(|e| {
        io::Error::other(format!(
            "could not create index log dir {}: {e}",
            log_dir.display()
        ))
    })?;
    restrict_permissions(&log_dir, 0o700);
    let log_file = std::fs::File::create(log_dir.join("daemon.log")).map_err(|e| {
        io::Error::other(format!(
            "could not create {}: {e}",
            log_dir.join("daemon.log").display()
        ))
    })?;
    restrict_permissions(&log_dir.join("daemon.log"), 0o600);
    // Separate fds for stdout/stderr so both capture the child's diagnostics.
    let log_err = log_file
        .try_clone()
        .map_err(|e| io::Error::other(format!("could not duplicate index log fd: {e}")))?;
    let exe = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("fog"));
    let mut cmd = std::process::Command::new(&exe);
    cmd.args([
        "index",
        "serve",
        "--foreground",
        "--port",
        &port.to_string(),
    ])
    .env("FOG_INDEX_CHILD", "1")
    .env("FOG_INDEX_PORT", port.to_string())
    .env("FOG_INDEX_NETWORK", network)
    .stdin(Stdio::null())
    .stdout(log_file)
    .stderr(log_err);
    crate::process::detach_command(&mut cmd);
    let mut child = cmd
        .spawn()
        .map_err(|e| io::Error::other(format!("could not spawn index server: {e}")))?;
    let pid = child.id();
    // Record the pid so `maybe_terminate_if_no_instances` can find it later.
    let _ = std::fs::write(index_pid_path(port), pid.to_string());
    // Wait for it to bind before reporting success (mirrors `daemonize`).
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(10);
    loop {
        if server_started(port) {
            println!("index server started in background (pid {pid}) on :{port}");
            println!("  status: curl http://127.0.0.1:{port}/api/services");
            println!("  stop:   fog index kill");
            println!("  logs:   {}", log_dir.join("daemon.log").display());
            println!("  log dir: {}", log_dir.display());
            return Ok(());
        }
        if child.try_wait().ok().flatten().is_some() {
            let _ = std::fs::remove_file(index_pid_path(port));
            return Err(io::Error::other(format!(
                "index server (pid {pid}) exited during startup; logs: {}",
                log_dir.display()
            )));
        }
        if std::time::Instant::now() >= deadline {
            return Err(io::Error::other(format!(
                "index server (pid {pid}) did not bind within 10s; logs: {}",
                log_dir.display()
            )));
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    }
}

/// Runs the index server in the foreground until killed. Used by
/// `fog index serve --foreground` and by the detached child spawned in
/// [`serve_detached`] (which sets `FOG_INDEX_CHILD=1`).
pub fn serve_foreground(port: u16, network: String) -> io::Result<()> {
    // Drop the detach marker so it does not leak into spawned helpers.
    // SAFETY: the process is still single-threaded at this point.
    if std::env::var_os("FOG_INDEX_CHILD").is_some() {
        unsafe { std::env::remove_var("FOG_INDEX_CHILD") };
    }
    serve_blocking(port, network)
}

/// Launches the index server as a detached background process (`fog index
/// serve --foreground` as the child), so it survives any individual fog
/// instance exiting. If it is already running this is a no-op.
fn spawn_server(cfg: &RouterConfig) -> Result<(), String> {
    let port = cfg.index_port.unwrap_or(DEFAULT_INDEX_PORT);
    if server_started(port) {
        return Ok(());
    }
    let log_dir = index_log_dir(port);
    let _ = std::fs::create_dir_all(&log_dir);
    restrict_permissions(&log_dir, 0o700);
    let log_file = std::fs::File::create(log_dir.join("daemon.log")).and_then(|f| {
        let err = f.try_clone()?;
        Ok((f, err))
    });
    restrict_permissions(&log_dir.join("daemon.log"), 0o600);
    let exe = std::env::current_exe().unwrap_or_else(|_| std::path::PathBuf::from("fog"));
    let mut cmd = std::process::Command::new(&exe);
    // `--foreground`: the child must block; this parent does the detaching.
    // (Plain `index serve` now detaches itself, which would double-fork here.)
    cmd.args([
        "index",
        "serve",
        "--foreground",
        "--port",
        &port.to_string(),
    ])
    .env("FOG_INDEX_CHILD", "1")
    .env("FOG_INDEX_PORT", port.to_string())
    .env("FOG_INDEX_NETWORK", &cfg.shared_network)
    .stdin(std::process::Stdio::null());
    match log_file {
        Ok((out, err)) => {
            cmd.stdout(out).stderr(err);
        }
        Err(_) => {
            cmd.stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null());
        }
    }
    crate::process::detach_command(&mut cmd);
    let mut child = cmd
        .spawn()
        .map_err(|e| format!("could not spawn index server: {e}"))?;
    let pid = child.id();
    // Record the pid so `maybe_terminate_if_no_instances` can find it later.
    let _ = std::fs::write(index_pid_path(port), pid.to_string());
    // Wait briefly for it to bind before reporting success.
    for _ in 0..25 {
        if server_started(port) {
            return Ok(());
        }
        if child.try_wait().ok().flatten().is_some() {
            let _ = std::fs::remove_file(index_pid_path(port));
            return Err(format!("index server (pid {pid}) exited during startup"));
        }
        std::thread::sleep(std::time::Duration::from_millis(200));
    }
    // Timed out — clean up the stale pidfile if the server never came up.
    if !server_started(port) {
        let _ = std::fs::remove_file(index_pid_path(port));
    }
    Err(format!("index server (pid {pid}) did not bind within 5s"))
}

/// Entry point for the `fog index serve` subcommand without flags.
/// Kept for programmatic use: runs the standalone index server in the
/// foreground until killed (env `FOG_INDEX_PORT`/`FOG_INDEX_NETWORK`).
/// The CLI (`main.rs`) detaches by default and only calls this via
/// `--foreground`.
pub fn serve() -> io::Result<()> {
    let port: u16 = std::env::var("FOG_INDEX_PORT")
        .ok()
        .and_then(|p| p.parse().ok())
        .unwrap_or(DEFAULT_INDEX_PORT);
    let network = std::env::var("FOG_INDEX_NETWORK").unwrap_or_else(|_| "fog-router".to_string());
    serve_blocking(port, network)
}

/// Blocks forever serving the embedded SPA on loopback `port` (127.0.0.1 only).
/// Write paths (`POST /api/instances/*/services/*/action`, `/kill`, `/launch`,
/// `/api/server/*`) are localhost-only by bind address — do not expose this
/// port externally. Any local process can still call them.
fn serve_blocking(port: u16, network: String) -> io::Result<()> {
    CURRENT_INDEX_PORT.store(port, std::sync::atomic::Ordering::SeqCst);
    // Record this server's pid for `maybe_terminate_if_no_instances`.
    let _ = std::fs::write(index_pid_path(port), std::process::id().to_string());
    // Self-terminate when no fog instance has been alive for a while, so a
    // crashed last instance (no cleanup hook) still brings the server down.
    std::thread::spawn(move || {
        let mut idle_ticks: u32 = 0;
        loop {
            std::thread::sleep(std::time::Duration::from_secs(5));
            let instances = crate::ipc::find_instances().unwrap_or_default();
            let any_alive = instances
                .iter()
                .any(|(_, p)| crate::ipc::query_status(p).is_ok());
            if any_alive {
                idle_ticks = 0;
            } else {
                idle_ticks += 1;
                // 4 ticks = ~20s of continuous idleness before exiting.
                if idle_ticks >= 4 {
                    let _ = std::fs::remove_file(index_pid_path(port));
                    std::process::exit(0);
                }
            }
        }
    });

    let rt = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|e| io::Error::other(e.to_string()))?;
    let result =
        rt.block_on(async move {
            let addr = format!("127.0.0.1:{port}");
            let listener = tokio::net::TcpListener::bind(&addr)
                .await
                .map_err(|e| io::Error::other(format!("bind {addr}: {e}")))?;
            // The embedded index server is where the web UI (and, via the vite dev
            // proxy, the dev UI) is actually reached, so it must serve the built-in
            // terminal gateway too — otherwise `/ws/terminal` would fall through to
            // the SPA fallback and the browser upgrade would fail. The standalone
            // server uses the gateway's default hardening limits (it has no
            // per-script `TerminalConfig`).
            let terminal = std::sync::Arc::new(crate::config::TerminalConfig::default());
            let terminal_sessions =
                std::sync::Arc::new(crate::terminal_ws::SessionsRegistry::default());
            loop {
                let Ok((stream, peer)) = listener.accept().await else {
                    continue;
                };
                let peer_ip = peer.ip().to_string();
                let io = TokioIo::new(stream);
                let network = network.clone();
                let terminal = terminal.clone();
                let terminal_sessions = terminal_sessions.clone();
                tokio::spawn(async move {
                    let svc = service_fn(move |req: Request<hyper::body::Incoming>| {
                        let network = network.clone();
                        let terminal = terminal.clone();
                        let terminal_sessions = terminal_sessions.clone();
                        let peer_ip = peer_ip.clone();
                        async move {
                            serve_index(&network, req, terminal, terminal_sessions, peer_ip).await
                        }
                    });
                    let _ = http1::Builder::new()
                        .serve_connection(io, svc)
                        .with_upgrades()
                        .await;
                });
            }
        });
    let _ = std::fs::remove_file(index_pid_path(port));
    result
}

/// Guards state-changing routes against cross-origin "simple" requests.
///
/// The embedded server binds loopback only, but a browser on any site the user
/// visits can still fire a cross-origin `POST` (a CORS "simple" request needs
/// no preflight) that launches or kills fog instances. A browser attaches
/// either `Sec-Fetch-Site` or `Origin` to such a request; a non-browser client
/// such as `curl` sends neither and is allowed, since it is not subject to the
/// browser's same-origin enforcement.
fn write_request_allowed(headers: &hyper::HeaderMap) -> bool {
    if let Some(site) = headers.get("sec-fetch-site").and_then(|v| v.to_str().ok())
        && site != "same-origin"
        && site != "none"
    {
        return false;
    }
    if let Some(origin) = headers
        .get(hyper::header::ORIGIN)
        .and_then(|v| v.to_str().ok())
    {
        if origin.eq_ignore_ascii_case("null") {
            return false;
        }
        let Some((_scheme, origin_authority)) = origin.split_once("://") else {
            return false;
        };
        let Some(host) = headers
            .get(hyper::header::HOST)
            .and_then(|v| v.to_str().ok())
        else {
            return false;
        };
        if crate::terminal_ws::normalize_authority(origin_authority)
            != crate::terminal_ws::normalize_authority(host)
        {
            return false;
        }
    }
    true
}

/// Defense-in-depth for the two body-parsing routes: a request that carries a
/// `Content-Type` must declare JSON. A missing header is allowed so non-browser
/// clients keep working; the origin guard is the primary protection.
fn json_content_type_allowed(headers: &hyper::HeaderMap) -> bool {
    match headers
        .get(hyper::header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
    {
        Some(ct) => ct
            .trim_start()
            .to_ascii_lowercase()
            .starts_with("application/json"),
        None => true,
    }
}

/// Rebuilds a terminal-gateway response with this server's body type. The
/// gateway's responses are fully buffered (empty body on 101, short text on
/// 401/429), so collecting is cheap and lossless.
async fn rebuild_response<B>(resp: hyper::Response<B>) -> Response<RespBody>
where
    B: hyper::body::Body<Data = Bytes>,
{
    let (parts, body) = resp.into_parts();
    let bytes = match body.collect().await {
        Ok(collected) => collected.to_bytes(),
        Err(_) => Bytes::new(),
    };
    Response::from_parts(parts, Full::new(bytes).boxed())
}

/// Handles the built-in `/ws/terminal` WebSocket upgrade.
///
/// `?service=<name>` attaches to a running service; `?live=1` requests live
/// emulation of the same PTY the TUI is showing (bidirectional, same process),
/// rather than a fresh shell in the service's workdir.
async fn handle_terminal_route(
    req: Request<Incoming>,
    terminal: std::sync::Arc<crate::config::TerminalConfig>,
    terminal_sessions: std::sync::Arc<crate::terminal_ws::SessionsRegistry>,
    peer_ip: String,
) -> Response<RespBody> {
    let service = query_param(req.uri().query(), "service");
    let live = query_param(req.uri().query(), "live")
        .is_some_and(|v| v == "1" || v.eq_ignore_ascii_case("true"));
    if live && service.is_some() {
        let svc = service.clone().unwrap();
        // Live attach must be a known running service, else 404.
        let running = discover_fog_instances()
            .iter()
            .any(|i| i.services.iter().any(|s| s.name == svc && s.running));
        if !running {
            return api_error(StatusCode::NOT_FOUND, "unknown or not running service");
        }
        let resp = crate::terminal_ws::handle_live_terminal_upgrade(
            req,
            terminal,
            terminal_sessions,
            peer_ip,
            svc,
            "127.0.0.1",
        )
        .await
        .expect("live terminal upgrade handler is infallible");
        return rebuild_response(resp).await;
    }
    let target = service.as_ref().and_then(|s| resolve_service_target(s));
    // An explicitly requested service that could not be resolved (not a
    // running service, or its workdir is unknown) is a 404, not a shell.
    if service.is_some() && target.is_none() {
        return api_error(StatusCode::NOT_FOUND, "unknown or not running service");
    }
    let resp = crate::terminal_ws::handle_terminal_upgrade(
        req,
        terminal,
        terminal_sessions,
        peer_ip,
        target,
        "127.0.0.1",
    )
    .await
    .expect("terminal upgrade handler is infallible");
    rebuild_response(resp).await
}

/// Routes embedded-server requests:
///   - `/ws/terminal` → the built-in terminal WebSocket gateway (live PTY)
///   - `/logs/stream` → SSE stream of a container's `docker logs -f`
///   - `/api/logs/history` → one-shot JSON window of older log lines
///     (`?service=&[pid=]&[tail=]&[offset=]`) for scroll-up backfill
///   - `/api/...`     → JSON API endpoints consumed by the SPA
///   - `/api/instances/{pid}/services/{name}/action` → `POST` a service action
///     to a running fog instance over its IPC socket
///   - any other path → an embedded SPA asset if present, else 404
///
/// The request is taken by value so the `action` route can consume its body;
/// every other route ignores it.
async fn serve_index(
    network: &str,
    req: Request<Incoming>,
    terminal: std::sync::Arc<crate::config::TerminalConfig>,
    terminal_sessions: std::sync::Arc<crate::terminal_ws::SessionsRegistry>,
    peer_ip: String,
) -> Result<Response<RespBody>, Infallible> {
    let method = req.method().clone();
    let path = req.uri().path().to_string();

    // State-changing routes are dispatched before the SPA fallback. Loopback
    // binding alone does not stop a web page the user visits from firing a
    // cross-origin "simple" POST (no preflight), so reject any write route that
    // a browser marks as coming from another origin.
    let is_write_route = parse_action_route(&path).is_some()
        || parse_kill_route(&path).is_some()
        || path == "/api/launch"
        || path == "/api/server/kill"
        || path == "/api/server/restart"
        || parse_restart_route(&path).is_some();
    if is_write_route && !write_request_allowed(req.headers()) {
        return Ok(api_error(
            StatusCode::FORBIDDEN,
            "cross-origin request rejected",
        ));
    }

    // The terminal gateway is a built-in WebSocket endpoint, so it must be
    // served before any static/API routing. Without this the browser's
    // `/ws/terminal` upgrade would be answered with the SPA fallback and the
    // connection would fail immediately.
    if crate::terminal_ws::is_terminal_upgrade(&req) {
        return Ok(handle_terminal_route(req, terminal, terminal_sessions, peer_ip).await);
    }

    // The action route consumes the request body (and forwards to a blocking
    // IPC call), so handle it before the path-only dispatch below.
    if let Some((pid, name)) = parse_action_route(&path) {
        if !json_content_type_allowed(req.headers()) {
            return Ok(api_error(
                StatusCode::BAD_REQUEST,
                "unsupported content-type",
            ));
        }
        let (_, body) = req.into_parts();
        let bytes = match body.collect().await {
            Ok(collected) => collected.to_bytes(),
            Err(_) => Bytes::new(),
        };
        return Ok(
            handle_action_request(&method, pid, name, &bytes, resolve_instance_socket).await,
        );
    }

    // The kill route is a no-body POST forwarded to the IPC socket.
    if let Some(pid) = parse_kill_route(&path) {
        return Ok(handle_kill_request(&method, pid).await);
    }

    // The launch route consumes the request body and can block for up to ~60s
    // while waiting for the daemon to become ready, so handle it before the
    // path-only dispatch below.
    if path == "/api/launch" {
        if !json_content_type_allowed(req.headers()) {
            return Ok(api_error(
                StatusCode::BAD_REQUEST,
                "unsupported content-type",
            ));
        }
        let (_, body) = req.into_parts();
        let bytes = match body.collect().await {
            Ok(collected) => collected.to_bytes(),
            Err(_) => Bytes::new(),
        };
        return Ok(handle_launch_request(&method, &bytes).await);
    }

    if path == "/api/server/kill" {
        return Ok(handle_server_kill_request(&method).await);
    }
    if path == "/api/server/restart" {
        return Ok(handle_server_restart_request(&method).await);
    }
    if let Some(pid) = parse_restart_route(&path) {
        return Ok(handle_instance_restart_request(&method, pid).await);
    }

    // `/api/services` supports `?withInternal=1` to include non-Traefik compose services
    // (e.g. postgres) for the logs picker. Default is Traefik-only. Blocking docker
    // calls are offloaded so the current_thread runtime is not stalled.
    if path == "/api/services" {
        let query = req.uri().query().map(|s| s.to_string());
        let net = network.to_string();
        let resp =
            tokio::task::spawn_blocking(move || api_services_with_query(&net, query.as_deref()))
                .await
                .unwrap_or_else(|e| api_error(StatusCode::INTERNAL_SERVER_ERROR, &e.to_string()));
        return Ok(resp);
    }

    // Per-project icon: reads the owning project's configured file (or
    // redirects to its configured URL). Filesystem access is offloaded so the
    // current_thread runtime is not stalled.
    if let Some(name) = parse_project_icon_route(&path) {
        let name = name.to_string();
        let if_none_match = req
            .headers()
            .get(hyper::header::IF_NONE_MATCH)
            .and_then(|v| v.to_str().ok())
            .map(str::to_string);
        let resp =
            tokio::task::spawn_blocking(move || api_project_icon(&name, if_none_match.as_deref()))
                .await
                .unwrap_or_else(|e| api_error(StatusCode::INTERNAL_SERVER_ERROR, &e.to_string()));
        return Ok(resp);
    }

    match path.as_str() {
        "/logs/stream" => Ok(serve_logs_stream(&req).await),
        "/api/logs/history" => Ok(serve_logs_history(&req).await),
        "/api/status" => Ok(api_status()),
        "/api/config" => Ok(api_config()),
        "/api/health" => Ok(api_health()),
        "/api/launch/targets" => Ok(api_launch_targets_method(&method)),
        _ if path.starts_with("/api/") => Ok(api_not_found()),
        _ => {
            let accept_encoding = req
                .headers()
                .get(hyper::header::ACCEPT_ENCODING)
                .and_then(|v| v.to_str().ok())
                .unwrap_or("");
            Ok(serve_spa_fallback(&path, accept_encoding))
        }
    }
}

/// Parses `/api/instances/{pid}/services/{name}/action` from a path, returning
/// the raw `pid` and service `name` segments on a structural match.
fn parse_action_route(path: &str) -> Option<(&str, &str)> {
    let rest = path.strip_prefix("/api/instances/")?;
    let mut seg = rest.split('/');
    let pid = seg.next()?;
    if seg.next() != Some("services") {
        return None;
    }
    let name = seg.next()?;
    if seg.next() != Some("action") {
        return None;
    }
    // No trailing segments allowed.
    if seg.next().is_some() {
        return None;
    }
    Some((pid, name))
}

/// Resolves the IPC socket path for a fog instance PID, defaulting to the
/// standard `$TMPDIR/fog-<pid>.sock` location. Factored out so tests can point
/// the action handler at a custom socket.
fn resolve_instance_socket(pid: u32) -> PathBuf {
    crate::ipc::socket_path(pid)
}

/// Request body for `POST /api/instances/{pid}/services/{name}/action`.
///
/// The action uses [`crate::ipc::ServiceAction`] (serde `snake_case`), so only
/// `start` / `stop` / `restart` deserialize; anything else (or a missing
/// `action`) fails to parse and is rejected with a 400.
#[derive(serde::Deserialize)]
struct ServiceActionBody {
    action: crate::ipc::ServiceAction,
}

/// Parses `/api/instances/{pid}/kill` from a path, returning the pid string.
fn parse_kill_route(path: &str) -> Option<&str> {
    let rest = path.strip_prefix("/api/instances/")?;
    let (pid, tail) = rest.split_once('/')?;
    if tail != "kill" {
        return None;
    }
    Some(pid)
}

/// Parses `/api/instances/{pid}/restart` from a path, returning the pid string.
fn parse_restart_route(path: &str) -> Option<&str> {
    let rest = path.strip_prefix("/api/instances/")?;
    let (pid, tail) = rest.split_once('/')?;
    if tail != "restart" {
        return None;
    }
    Some(pid)
}

/// Handles `POST /api/instances/{pid}/kill` — sends a graceful shutdown
/// over the instance's IPC socket.
///
///   - non-`POST` → 404
///   - non-numeric pid → 400
///   - no socket file → 404
///   - success → 200 `{"ok":true}`
///   - IPC error → 502
async fn handle_kill_request(method: &hyper::Method, pid_str: &str) -> Response<RespBody> {
    if method != hyper::Method::POST {
        return api_not_found();
    }

    let Ok(pid) = pid_str.parse::<u32>() else {
        return api_error(StatusCode::BAD_REQUEST, "invalid pid");
    };

    let socket = resolve_instance_socket(pid);
    if !socket.exists() {
        return api_error(StatusCode::NOT_FOUND, "instance not found");
    }

    let outcome = tokio::task::spawn_blocking(move || crate::ipc::send_kill(&socket))
        .await
        .unwrap_or_else(|e| Err(io::Error::other(e.to_string())));

    match outcome {
        Ok(()) => {
            // The killed instance will run `maybe_terminate_if_no_instances`
            // on its own exit, but also schedule a server-side idle check
            // so the server exits even if that instance crashes before it.
            tokio::task::spawn_blocking(|| {
                std::thread::sleep(std::time::Duration::from_millis(800));
                maybe_terminate_if_no_instances(None);
            });
            json_response(&serde_json::json!({"ok":true}))
        }
        Err(e) => api_error(StatusCode::BAD_GATEWAY, &e.to_string()),
    }
}

/// Handles `POST /api/server/kill` — terminates the index server itself.
///
/// The response is sent before the server exits, so the client sees success.
async fn handle_server_kill_request(method: &hyper::Method) -> Response<RespBody> {
    if method != hyper::Method::POST {
        return api_not_found();
    }
    let port = {
        let p = CURRENT_INDEX_PORT.load(std::sync::atomic::Ordering::SeqCst);
        if p != 0 { p } else { DEFAULT_INDEX_PORT }
    };
    tokio::task::spawn_blocking(move || {
        std::thread::sleep(std::time::Duration::from_millis(200));
        let _ = terminate_server_on_port(port);
        std::process::exit(0);
    });
    json_response(&serde_json::json!({"ok":true}))
}

/// Handles `POST /api/server/restart` — kills then re-ensures the index server.
///
/// The restart is done by spawning a detached helper that revives the server
/// after this process exits, so the port is free when the new server binds.
async fn handle_server_restart_request(method: &hyper::Method) -> Response<RespBody> {
    if method != hyper::Method::POST {
        return api_not_found();
    }
    let current_port = CURRENT_INDEX_PORT.load(std::sync::atomic::Ordering::SeqCst);
    let port = if current_port != 0 {
        current_port
    } else {
        let cfg = load_runtime_config().router.unwrap_or_default();
        cfg.index_port.unwrap_or(DEFAULT_INDEX_PORT)
    };
    let network = std::env::var("FOG_INDEX_NETWORK").ok().unwrap_or_else(|| {
        load_runtime_config()
            .router
            .unwrap_or_default()
            .shared_network
            .clone()
    });
    tokio::task::spawn_blocking(move || {
        // Wait for the current server to release the port before relaunching.
        std::thread::sleep(std::time::Duration::from_millis(700));
        // Launch a detached `fog index serve --foreground`: the helper blocks
        // (plain `serve` would detach itself and double-fork).
        let exe = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("fog"));
        let mut cmd = std::process::Command::new(&exe);
        cmd.args(["index", "serve", "--foreground"])
            .env("FOG_INDEX_PORT", port.to_string())
            .env("FOG_INDEX_NETWORK", &network)
            .stdin(std::process::Stdio::null())
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null());
        crate::process::detach_command(&mut cmd);
        let _ = cmd.spawn();
        let _ = std::fs::remove_file(index_pid_path(port));
        std::process::exit(0);
    });
    json_response(&serde_json::json!({"ok":true, "port": port}))
}

/// Handles `POST /api/instances/{pid}/restart` — kills the instance and
/// relaunches it detached with the same script/config/branch.
async fn handle_instance_restart_request(
    method: &hyper::Method,
    pid_str: &str,
) -> Response<RespBody> {
    if method != hyper::Method::POST {
        return api_not_found();
    }
    let Ok(pid) = pid_str.parse::<u32>() else {
        return api_error(StatusCode::BAD_REQUEST, "invalid pid");
    };
    let socket = resolve_instance_socket(pid);
    if !socket.exists() {
        return api_error(StatusCode::NOT_FOUND, "instance not found");
    }
    let outcome = tokio::task::spawn_blocking(move || {
        // Query before killing to capture relaunch params.
        let status = crate::ipc::query_status(&socket)
            .map_err(|e| format!("could not query instance {pid}: {e}"))?;
        let script = status.script.clone();
        let config_dir = status.config_dir.clone().unwrap_or_else(|| ".".to_string());
        let config_path = std::path::PathBuf::from(&config_dir).join("fog.json");
        let config_path = if config_path.exists() {
            config_path
        } else {
            std::path::PathBuf::from(&config_dir)
        };
        let socket = resolve_instance_socket(pid);
        crate::ipc::send_kill(&socket).map_err(|e| e.to_string())?;
        // Wait for old instance to exit.
        for _ in 0..50 {
            if !crate::process::is_pid_alive(pid) && crate::ipc::query_status(&socket).is_err() {
                break;
            }
            std::thread::sleep(std::time::Duration::from_millis(100));
        }
        // Relaunch detached. config_path already points at the correct
        // worktree's fog.json, so no --branch is needed.
        let exe = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("fog"));
        let mut cmd = std::process::Command::new(&exe);
        cmd.arg("--config").arg(&config_path).arg(&script);
        cmd.env("FOG_DAEMON_CHILD", "1")
            .stdin(std::process::Stdio::null())
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null());
        crate::process::detach_command(&mut cmd);
        let mut child = cmd.spawn().map_err(|e| format!("could not restart: {e}"))?;
        let new_pid = child.id();
        let new_socket = crate::ipc::socket_path(new_pid);
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(60);
        loop {
            if crate::ipc::query_status(&new_socket).is_ok() {
                return Ok::<u32, String>(new_pid);
            }
            if child.try_wait().ok().flatten().is_some() {
                return Err(format!(
                    "restarted instance {new_pid} exited during startup"
                ));
            }
            if std::time::Instant::now() >= deadline {
                return Err(format!("restarted instance {new_pid} did not become ready"));
            }
            std::thread::sleep(std::time::Duration::from_millis(100));
        }
    })
    .await
    .unwrap_or(Err("spawn_blocking failed".to_string()));
    match outcome {
        Ok(new_pid) => json_response(&serde_json::json!({"ok":true, "pid": new_pid})),
        Err(e) => api_error(StatusCode::INTERNAL_SERVER_ERROR, &e),
    }
}

/// Handles `POST /api/instances/{pid}/services/{name}/action`.
///
/// Forward the action to the fog instance owning `pid` over its IPC socket.
/// Status code contract:
///   - non-`POST` method → 404 (treated like an unknown route, matching the
///     other path-only handlers)
///   - non-numeric `pid` → 400 `{"error":"invalid pid"}`
///   - invalid/missing `action` in the body → 400 `{"error":"invalid action"}`
///   - no socket file for the pid → 404 `{"error":"instance not found"}`
///   - success (even with `ok:false`) → 200 `{"ok":..,"reason":".."}`
///   - `send_service_action` io error (socket exists but the instance is
///     unreachable / connect fails / times out) → 502 `{"error":"<err>"}`
///
/// The 502 choice mirrors a reverse-proxy `BAD_GATEWAY`: the request reached a
/// real endpoint but the upstream fog instance did not answer — consistent with
/// the proxy treating an unreachable upstream as a gateway error. The 404 above
/// is reserved for the unambiguous "no instance socket at all" case.
async fn handle_action_request<F>(
    method: &hyper::Method,
    pid: &str,
    name: &str,
    body: &[u8],
    resolve: F,
) -> Response<RespBody>
where
    F: Fn(u32) -> PathBuf,
{
    // The action route only fires on POST; any other method is treated like an
    // unknown API route (404), matching the existing path-only handlers.
    if method != hyper::Method::POST {
        return api_not_found();
    }

    let Ok(pid) = pid.parse::<u32>() else {
        return api_error(StatusCode::BAD_REQUEST, "invalid pid");
    };

    // Parse the body into a typed request so the action must be a real
    // `ServiceAction` (`start`/`stop`/`restart`).
    let req: ServiceActionBody = match serde_json::from_slice(body) {
        Ok(r) => r,
        Err(_) => return api_error(StatusCode::BAD_REQUEST, "invalid action"),
    };

    let socket = resolve(pid);
    if !socket.exists() {
        return api_error(StatusCode::NOT_FOUND, "instance not found");
    }

    // send_service_action blocks for up to ~35s (IPC 30s control window +
    // margin); move it onto a blocking thread so the HTTP task is never
    // blocked. A panic inside is surfaced as an io error, never an unwrap.
    let socket_task = socket.clone();
    let name_task = name.to_string();
    let action = req.action;
    let outcome = tokio::task::spawn_blocking(move || {
        crate::ipc::send_service_action(&socket_task, &name_task, action)
    })
    .await
    .unwrap_or_else(|e| Err(io::Error::other(e.to_string())));

    match outcome {
        // The instance's verdict is reported verbatim: 200 even when the action
        // was refused (`ok:false`) with a human-readable reason.
        Ok(resp) => json_response(&serde_json::json!({
            "ok": resp.ok,
            "reason": resp.reason,
        })),
        Err(e) => api_error(StatusCode::BAD_GATEWAY, &e.to_string()),
    }
}

/// Maps a file path to a media type for the `Content-Type` header.
#[allow(dead_code)] // only reachable through build-generated code when SPA exists
fn mime_for(path: &str) -> &'static str {
    let ext = path.rsplit('.').next().unwrap_or("");
    match ext {
        "html" | "htm" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "avif" => "image/avif",
        "ico" => "image/x-icon",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "wasm" => "application/wasm",
        "webmanifest" => "application/manifest+json",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

/// Builds a reachable URL for a service entry: HTTP services use
/// `{scheme}://{hostname}/`; raw-TCP services exposed via `fog.expose` use
/// `http://{hostname}:{raw_port}/`.
fn entry_url(e: &IndexEntry) -> String {
    if e.port.is_empty() {
        match &e.raw_port {
            Some(rp) => format!("http://{}:{}/", e.hostname, rp),
            None => format!("http://{}/", e.hostname),
        }
    } else {
        let scheme = if e.tls { "https" } else { "http" };
        format!("{scheme}://{}/", e.hostname)
    }
}

/// One declared endpoint (endpoint) of an [`ApiService`].
#[derive(serde::Serialize, Clone)]
struct ApiEndpoint {
    /// Endpoint display name.
    name: String,
    /// Externally reachable URL for this endpoint, empty when it declares no
    /// routable `host`.
    url: String,
    /// Host-published port, empty when not declared.
    port: String,
    /// Optional PathPrefix the route combines with the host.
    #[serde(skip_serializing_if = "Option::is_none")]
    path_prefix: Option<String>,
    /// Per-endpoint health state (`healthy`/`unhealthy`/...).
    health: String,
}

/// A single service as reported by `GET /api/services`.
#[derive(serde::Serialize, Clone)]
struct ApiService {
    project: String,
    worktree: String,
    service: String,
    /// Docker container name (e.g. `redfox-main-api-1`). `/logs/stream`
    /// streams a container's logs by this name, so the picker must pass it
    /// rather than the compose service name.
    container: String,
    status: String,
    url: String,
    ports: Vec<String>,
    health: String,
    /// Fog PID for native (non-docker) services. When present, logs are
    /// streamed via `?pid=<pid>&service=<name>` (fog IPC) instead of docker.
    #[serde(skip_serializing_if = "Option::is_none")]
    pid: Option<u32>,
    /// Optional project icon (image URL or data URI) from the owning project's
    /// `fog.json` (`project.icon`). Omitted when unset.
    #[serde(skip_serializing_if = "Option::is_none")]
    icon: Option<String>,
    /// Declared endpoint endpoints of this service. Omitted when the
    /// service exposes a single implicit endpoint (the common case).
    #[serde(skip_serializing_if = "Vec::is_empty")]
    endpoints: Vec<ApiEndpoint>,
}

/// Converts a discovered [`IndexEntry`] into its JSON shape. Discovery only sees
/// running containers, so `status` is `running`; per-service `health` is not
/// available from docker here (it is reported by fog instances via `/api/health`).
fn api_service_from(e: IndexEntry) -> ApiService {
    let url = entry_url(&e);
    let ports = e.published;
    ApiService {
        project: e.project,
        worktree: e.worktree,
        service: e.service,
        container: e.container,
        status: "running".to_string(),
        url,
        ports,
        health: "unknown".to_string(),
        pid: None,
        icon: None,
        endpoints: Vec::new(),
    }
}

/// Builds the declared endpoint list for one instance service.
///
/// Resolves each tagged endpoint route's host/port into a URL. When a
/// endpoint declares no route, the matching docker-discovered entry (matched
/// by project/worktree/name) supplies its URL and published ports — so a
/// compose service that routes itself via Traefik labels (or exposes raw TCP
/// via `fog.expose`) keeps its link after being nested under the parent.
///
/// Health comes from the instance's per-endpoint reading when it is known,
/// otherwise from the parent service's health (a endpoint without its own
/// `health_check` inherits the parent's).
fn api_endpoints_for(
    inst: &FogInstance,
    service: &str,
    docker: &[ApiService],
    project: &str,
    worktree: &str,
) -> Vec<ApiEndpoint> {
    let svc_status = inst.services.iter().find(|s| s.name == service);
    let parent_health = svc_status
        .map(|s| s.health.clone())
        .unwrap_or_else(|| "unknown".to_string());
    let mut out = Vec::new();
    for route in &inst.native_routes {
        let Some(endpoint_name) = route.endpoint.as_deref() else {
            continue;
        };
        if route.service != service {
            continue;
        }
        // Resolve host/port templates with this instance's PortMap+branch. A
        // endpoint may declare neither (display + health only): url/port
        // stay empty.
        let host = crate::ports::resolve_template(&route.host, &inst.ports, inst.branch.as_deref())
            .map(|h| crate::ports::sanitize_hostname(&h))
            .unwrap_or_default();
        let mut port =
            crate::ports::resolve_template(&route.port, &inst.ports, inst.branch.as_deref())
                .unwrap_or_default();
        let mut url = if host.is_empty() {
            String::new()
        } else {
            format!("https://{}/", host)
        };
        // No fog-generated route: inherit the matching docker entry's URL/ports
        // (e.g. a compose service already routed by its own Traefik labels).
        // Prefer an exact worktree match; fall back to the sole entry for this
        // project+service (covers branch-agnostic/shared compose projects).
        if url.is_empty() {
            let matches: Vec<&ApiService> = docker
                .iter()
                .filter(|d| d.project.eq_ignore_ascii_case(project) && d.service == endpoint_name)
                .collect();
            let chosen = matches
                .iter()
                .find(|d| d.worktree == worktree)
                .copied()
                .or_else(|| (matches.len() == 1).then(|| matches[0]));
            if let Some(d) = chosen {
                url = d.url.clone();
                if port.is_empty() && !d.ports.is_empty() {
                    port = d.ports.join(", ");
                }
            }
        }
        let health = svc_status
            .and_then(|s| s.endpoints.iter().find(|ss| ss.name == endpoint_name))
            .map(|ss| ss.health.clone())
            .filter(|h| h != "unknown")
            .unwrap_or_else(|| parent_health.clone());
        out.push(ApiEndpoint {
            name: endpoint_name.to_string(),
            url,
            port,
            path_prefix: route.path_prefix.clone(),
            health,
        });
    }
    out
}

/// `GET /api/services`: every running compose service as JSON, so the SPA logs
/// picker can stream logs from any container. Native (non-docker) services
/// started via `ports` + `native_routes` are synthesized from fog instances so
/// they appear alongside docker services in the Services UI.
///
/// Query `?withInternal=1` (or `?internal=1`) opts into non-Traefik compose
/// services (e.g. `postgres`) so the logs picker can still see them. Default
/// is Traefik-only (`fog.expose` or `traefik.http.routers.*`) to avoid
/// unrelated `docker ps` entries like a stray `mongodb`.
/// Derives the `(project, worktree)` display group for an instance.
///
/// `project` keeps its original case; callers that compare against docker rows
/// lowercase it themselves. `worktree` is the branch sanitized down to a single
/// DNS label (`sanitize_hostname(...).split('.').next()`).
fn instance_group(inst: &FogInstance) -> (String, String) {
    let project = inst
        .project
        .as_deref()
        .map(project_name_from_common_dir)
        .unwrap_or_else(|| inst.script.clone());
    let raw_worktree = inst.branch.clone().unwrap_or_else(|| "default".to_string());
    let worktree = crate::ports::sanitize_hostname(&raw_worktree)
        .split('.')
        .next()
        .unwrap_or("default")
        .to_string();
    (project, worktree)
}

/// Declared-endpoint keys: `(project, worktree, endpoint)` for exact matches and
/// `(project, endpoint)` for branch-agnostic compose projects grouped as `shared`.
type DeclaredEndpoints = (
    std::collections::HashSet<(String, String, String)>,
    std::collections::HashSet<(String, String)>,
);

/// Collects the declared-endpoint keys for every instance, lowercasing the
/// project so it matches docker-derived `ApiService.project`.
fn declared_endpoint_keys(instances: &[FogInstance]) -> DeclaredEndpoints {
    let mut exact = std::collections::HashSet::new();
    let mut shared = std::collections::HashSet::new();
    for inst in instances {
        let (project, worktree) = instance_group(inst);
        let project = project.to_lowercase();
        for route in &inst.native_routes {
            if let Some(sub) = &route.endpoint {
                exact.insert((project.clone(), worktree.clone(), sub.clone()));
                shared.insert((project.clone(), sub.clone()));
            }
        }
    }
    (exact, shared)
}

/// Suppresses docker rows whose `(project, worktree, service)` is a declared
/// endpoint: those are nested under their parent instead of appearing as
/// separate top-level rows. A branch-agnostic compose project (e.g. a bare
/// `gems-infra` with no branch suffix) is grouped by docker under the `shared`
/// worktree even though its owning instance reports a real branch; for those,
/// match on project+service alone so they are still nested.
fn suppress_declared_docker(
    all_docker: &[ApiService],
    keys: &DeclaredEndpoints,
) -> Vec<ApiService> {
    let (exact, shared) = keys;
    all_docker
        .iter()
        .filter(|e| {
            let proj = e.project.to_lowercase();
            let exact_match =
                exact.contains(&(proj.clone(), e.worktree.clone(), e.service.clone()));
            let shared_match =
                e.worktree == "shared" && shared.contains(&(proj, e.service.clone()));
            !(exact_match || shared_match)
        })
        .cloned()
        .collect()
}

/// Adds top-level rows for an instance's running native routes. Endpoint routes
/// are skipped here — they are nested under their parent by
/// [`attach_declared_endpoints`].
fn synthesize_native_routes(
    list: &mut Vec<ApiService>,
    inst: &FogInstance,
    project: &str,
    worktree: &str,
) {
    // Build a map of service name -> health for quick lookup.
    let health_map: std::collections::HashMap<&str, &str> = inst
        .services
        .iter()
        .map(|s| (s.name.as_str(), s.health.as_str()))
        .collect();
    for route in &inst.native_routes {
        // Endpoint routes are nested under their parent (below), never listed
        // as separate top-level services.
        if route.endpoint.is_some() {
            continue;
        }
        let Some(svc_status) = inst.services.iter().find(|s| s.name == route.service) else {
            continue;
        };
        if !svc_status.running {
            continue;
        }
        // Resolve host and port templates with this instance's PortMap+branch.
        let host = match crate::ports::resolve_template(
            &route.host,
            &inst.ports,
            inst.branch.as_deref(),
        ) {
            Ok(h) => crate::ports::sanitize_hostname(&h),
            Err(_) => continue,
        };
        let port_str = match crate::ports::resolve_template(
            &route.port,
            &inst.ports,
            inst.branch.as_deref(),
        ) {
            Ok(p) => p,
            Err(_) => continue,
        };
        let port: u16 = match port_str.parse() {
            Ok(p) => p,
            Err(_) => continue,
        };
        // Native routes are always TLS-enabled (see router.rs), so use https.
        let url = format!("https://{}/", host);
        let health = health_map
            .get(route.service.as_str())
            .copied()
            .unwrap_or("unknown");
        // Avoid duplicating a docker entry that already covers this host (e.g. if a
        // service is both docker and native in different worktrees, keep both).
        if list
            .iter()
            .any(|e| e.service == route.service && e.worktree == worktree && e.project == project)
        {
            continue;
        }
        list.push(ApiService {
            project: project.to_string(),
            worktree: worktree.to_string(),
            service: route.service.clone(),
            container: format!("fog-{}-{}", inst.pid, route.service),
            status: "running".to_string(),
            url,
            ports: vec![format!("0.0.0.0:{}->{}/tcp", port, port)],
            health: health.to_string(),
            pid: Some(inst.pid),
            icon: None,
            endpoints: Vec::new(),
        });
    }
}

/// Attaches declared endpoints to their parent service's entry, creating the
/// parent entry when docker/native discovery did not list it (e.g. a
/// compose-stack launcher that is not itself a container). Also adds running
/// native services that have no native route so they still appear in the
/// directory.
fn attach_declared_endpoints(
    list: &mut Vec<ApiService>,
    inst: &FogInstance,
    project: &str,
    worktree: &str,
    all_docker: &[ApiService],
    docker_entries: &[IndexEntry],
) {
    for svc in &inst.services {
        if !svc.running {
            continue;
        }
        let subs = api_endpoints_for(inst, &svc.name, all_docker, project, worktree);
        if !subs.is_empty() {
            if let Some(existing) = list
                .iter_mut()
                .find(|e| e.service == svc.name && e.worktree == worktree && e.project == project)
            {
                if existing.endpoints.is_empty() {
                    existing.endpoints = subs;
                }
            } else {
                list.push(ApiService {
                    project: project.to_string(),
                    worktree: worktree.to_string(),
                    service: svc.name.clone(),
                    container: format!("fog-{}-{}", inst.pid, svc.name),
                    status: "running".to_string(),
                    url: String::new(),
                    ports: Vec::new(),
                    health: svc.health.clone(),
                    pid: Some(inst.pid),
                    icon: None,
                    endpoints: subs,
                });
            }
            continue;
        }
        // Native services with a route are already listed above.
        if inst.native_routes.iter().any(|r| r.service == svc.name) {
            continue;
        }
        // Show running native services not already listed.
        let already = list
            .iter()
            .any(|e| e.service == svc.name && e.worktree == worktree && e.project == project);
        if already {
            continue;
        }
        // A service that docker already reported is listed by docker, not here.
        let is_docker = docker_entries
            .iter()
            .any(|e| e.service == svc.name && e.worktree == worktree);
        if is_docker {
            continue;
        }
        list.push(ApiService {
            project: project.to_string(),
            worktree: worktree.to_string(),
            service: svc.name.clone(),
            container: format!("fog-{}-{}", inst.pid, svc.name),
            status: "running".to_string(),
            url: String::new(),
            ports: Vec::new(),
            health: svc.health.clone(),
            pid: Some(inst.pid),
            icon: None,
            endpoints: Vec::new(),
        });
    }
}

fn api_services_with_query(_network: &str, query: Option<&str>) -> Response<RespBody> {
    let with_internal = query
        .map(parse_query)
        .map(|m| {
            m.get("withInternal")
                .or_else(|| m.get("with_internal"))
                .or_else(|| m.get("internal"))
                .is_some_and(|v| v == "1" || v.eq_ignore_ascii_case("true"))
        })
        .unwrap_or(false);
    // Collect running fog roots once and reuse for docker filtering and native synthesis.
    let instances = discover_fog_instances();
    let icons = project_icons(&instances);
    let allowed_roots: std::collections::HashSet<PathBuf> = instances
        .iter()
        .filter_map(|i| i.config_dir.as_deref().map(PathBuf::from))
        .map(|p| p.canonicalize().unwrap_or(p))
        .collect();
    let docker_entries = discover_compose_containers_filtered_scoped(with_internal, &allowed_roots);
    // Every docker-discovered service, before suppression. Used both for the
    // top-level list and to let a declared endpoint inherit the URL/ports of
    // a matching compose service that manages its own routing.
    let all_docker: Vec<ApiService> = docker_entries
        .iter()
        .cloned()
        .map(api_service_from)
        .collect();
    let declared = declared_endpoint_keys(&instances);
    let mut list = suppress_declared_docker(&all_docker, &declared);
    for inst in &instances {
        let (project, worktree) = instance_group(inst);
        synthesize_native_routes(&mut list, inst, &project, &worktree);
        attach_declared_endpoints(
            &mut list,
            inst,
            &project,
            &worktree,
            &all_docker,
            &docker_entries,
        );
    }
    // Attach each project's configured icon (if any) to every service in it, so
    // the Services UI can group and show it once per project card.
    for svc in &mut list {
        if svc.icon.is_none() {
            svc.icon = icons.get(&svc.project).cloned();
        }
    }
    json_response(&list)
}

/// One running fog instance as reported by `GET /api/status`.
#[derive(serde::Serialize)]
